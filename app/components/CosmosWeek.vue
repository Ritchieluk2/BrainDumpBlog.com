<script setup lang="ts">
/** A week of morning dumps in the reader's chosen art style (a galaxy by default). */
import type { GalaxyDay } from '#shared/utils/cosmos'
import type { MoodMap } from '#shared/utils/moods'
import { renderWeek, type ArtStyle } from '#shared/utils/cosmos-styles'

const props = defineProps<{
  days: GalaxyDay[]
  seed: string
  title?: string
  art?: ArtStyle
  /** Override the reader's night-mode preference (for previews). A string, not a
   *  boolean, because Vue turns a missing boolean prop into `false`. */
  theme?: 'day' | 'night'
  /** Override the reader's colors and shapes (for previews). */
  moods?: MoodMap
}>()

const prefs = usePreferences()
// Drawn in the browser, not on the server: keeps each server request well under
// Cloudflare's free-plan CPU limit, and avoids a light/dark flash for "System".
const mounted = ref(false)
onMounted(() => { mounted.value = true })
const svg = computed(() => !mounted.value ? '' :
  renderWeek(props.art ?? prefs.art.value, props.days, {
    seed: props.seed,
    title: props.title,
    night: props.theme ? props.theme === 'night' : prefs.night.value,
    moods: props.moods ?? prefs.moods.value
  })
)
</script>

<template>
  <!-- eslint-disable-next-line vue/no-v-html -- SVG is generated by our own code from numbers only -->
  <div class="cosmos" :class="{ 'is-loading': !svg }" v-html="svg" />
</template>

<style scoped>
.cosmos { width: 100%; aspect-ratio: 1; }
.cosmos.is-loading { background: var(--bd-line); opacity: 0.5; }
.cosmos :deep(svg) { width: 100%; height: 100%; display: block; }
</style>
